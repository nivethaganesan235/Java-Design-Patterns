package Decorator;

public class Student {
	String studentId;
    String name;
    String branch;
    String email;
    String phone;


    public Student(String studentId, String name, String branch, String email, String phone) {

        this.studentId = studentId;
        this.name = name;
        this.branch = branch;
        this.email = email;
        this.phone = phone;
    }

}
